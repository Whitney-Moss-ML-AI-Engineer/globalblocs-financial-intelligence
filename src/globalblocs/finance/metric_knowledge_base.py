def metric_catalog(): return METRIC_KNOWLEDGE_BASE.copy()
def get_metric(metric_id: int): return METRIC_KNOWLEDGE_BASE[metric_id-1] if 1 <= metric_id <= len(METRIC_KNOWLEDGE_BASE) else None
def search_metrics(query: str="", category: str|None=None):
    q=(query or "").lower()
    return [m for m in METRIC_KNOWLEDGE_BASE if (not category or m["category"]==category) and (not q or q in (m["name"]+" "+m["category"]).lower())]
def category_summary(): return {k:sum(m["category"]==k for m in METRIC_KNOWLEDGE_BASE) for k in CATEGORY_COUNTS}
def validate_catalog():
    names=[m["name"] for m in METRIC_KNOWLEDGE_BASE]
    return {"count":len(names),"unique":len(set(names)),"categories":category_summary(),"valid":len(names)==350 and len(set(names))==350 and category_summary()==CATEGORY_COUNTS}
