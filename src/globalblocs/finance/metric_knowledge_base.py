def _recommended(name: str, category: str) -> list[str]:
    n=name.lower()
    if "correlation" in n or "covariance" in n: return ["heatmap","scatter","correlation_matrix"]
    if "drawdown" in n: return ["drawdown","line","area"]
    if "volatility" in n or "var" in n or "risk" in n: return ["line","histogram","box","heatmap"]
    if "revenue" in n or "earnings" in n or "growth" in n or "margin" in n: return ["line","bar","area","waterfall"]
    if "price" in n or "momentum" in n: return ["line","candlestick","volume","histogram"]
    families={"return_performance":["line","bar","area","histogram","box"],"portfolio_risk":["line","drawdown","histogram","heatmap","risk_contribution"],"risk_adjusted":["line","bar","scatter","histogram","radar"],"quantitative_finance":["line","bar","area","scatter","heatmap"]}
    return families[category]

